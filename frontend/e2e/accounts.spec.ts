/** Follow real Admin create/detail and duplicate persistence journeys without network mocks. */
import { test, expect, signIn } from './fixtures';
import { UserView } from '../src/app/core/api.models';
import { randomUUID } from 'node:crypto';
// Keep one entry navigation; subsequent transitions use actual shell links and browser Back.
test('Admin creates a safe account, revisits detail and duplicate failure preserves persisted data', async ({ page }) => {
  test.info().annotations.push({ type: 'expected-http-console-status', description: '409' });
  const username = `e2e.${randomUUID().replace(/-/g, '')}`;
  const password = `Synthetic-${randomUUID()}`;
  const writes: string[] = [];
  page.on('request', request => { if (['POST', 'PUT', 'DELETE'].includes(request.method()) && new URL(request.url()).pathname.startsWith('/api/users')) writes.push(request.method()); });
  await page.goto('/');
  await page.getByRole('main').getByRole('link', { name: 'Sign in', exact: true }).click();
  await signIn(page, 'Admin');
  await page.getByRole('navigation').getByRole('link', { name: 'New account', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'New account', exact: true })).toBeVisible();
  expect(writes).toEqual([]);
  await page.getByLabel('Username', { exact: true }).fill(username);
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByLabel('City (optional)', { exact: true }).fill('Synthetic journey city');
  await page.getByLabel('Aadhaar identifier (optional)', { exact: true }).fill('SYNTHETIC-AADHAAR');
  await page.getByLabel('PAN identifier (optional)', { exact: true }).fill('SYNTHETIC-PAN');
  const createdResponse = page.waitForResponse(r => new URL(r.url()).pathname === '/api/users' && r.request().method() === 'POST');
  const detailResponse = page.waitForResponse(r => new URL(r.url()).pathname.startsWith('/api/users/') && r.request().method() === 'GET');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Creating account…' })).toBeDisabled();
  const created = await createdResponse; expect(created.status()).toBe(201);
  const account = await created.json() as UserView;
  expect(Object.keys(account).sort()).toEqual(['address', 'city', 'country', 'created_at', 'education', 'id', 'is_active', 'updated_at', 'username']);
  expect(account.username).toBe(username); expect(account.city).toBe('Synthetic journey city');
  const detail = await detailResponse; expect(detail.status()).toBe(200); expect(await detail.json()).toEqual(account);
  await expect(page).toHaveURL(`/users/${account.id}`);
  await expect(page.getByRole('heading', { name: 'Account details' })).toBeVisible();
  await expect(page.getByRole('main')).toContainText(account.username);
  await expect(page.getByRole('main')).toContainText(account.city!);
  await expect(page.getByRole('main')).not.toContainText('SYNTHETIC-PAN');
  expect(writes).toEqual(['POST']);
  await page.getByRole('main').getByRole('link', { name: 'New account', exact: true }).click();
  await page.getByLabel('Username', { exact: true }).fill(username);
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByLabel('City (optional)', { exact: true }).fill('Should not persist');
  const conflictResponse = page.waitForResponse(r => new URL(r.url()).pathname === '/api/users' && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  const conflict = await conflictResponse; expect(conflict.status()).toBe(409); expect((await conflict.json()).type).toBe('username_conflict');
  await expect(page.getByRole('alert')).toContainText('Username is already in use');
  await expect(page.getByLabel('Password', { exact: true })).toHaveValue('');
  const persistedResponse = page.waitForResponse(r => new URL(r.url()).pathname === `/api/users/${account.id}` && r.request().method() === 'GET');
  await page.goBack();
  const persisted = await persistedResponse; expect(persisted.status()).toBe(200); expect(await persisted.json()).toEqual(account);
  await expect(page.getByRole('main')).toContainText('Synthetic journey city');
  await expect(page.getByRole('main')).not.toContainText('Should not persist'); expect(writes).toEqual(['POST', 'POST']);
  await page.screenshot({ path: test.info().outputPath('account-detail.png'), fullPage: true });
});
